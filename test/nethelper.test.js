// The router helper (PowerShell) against the pretend router: pair, read, allow, block, whitelist on/off, test, probe.
'use strict';
const assert = require('assert');
const { spawn } = require('child_process');
const fs = require('fs'), os = require('os'), path = require('path');
const startRouter = require('./routermock');
const PWSH = process.env.PWSH || 'pwsh';
(async () => {
  const r = await startRouter({ devices: [['192.168.1.20', '3C:52:82:1A:4F:09', 'POS-PC', 'Online'], ['192.168.1.34', 'A4:83:E7:22:91:BC', 'Earth-phone', 'Online'], ['192.168.1.57', 'D2:6F:3B:90:AE:14', 'android-dhcp-12', 'Online']] });
  r.st.topo = [['D2:6F:3B:90:AE:14', 'HUAWEI-P30', '192.168.1.57'], ['46:6B:60:A4:95:88', 'supaporn-s-Z-Flip6', '192.168.1.101']];
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'emnet-'));
  fs.copyFileSync(path.join(__dirname, '..', 'tools', 'windows', 'net-profile.json'), path.join(dir, 'net-profile.json'));
  const port = 18765 + Math.floor(Math.random() * 500);
  const ps = spawn(PWSH, ['-NoProfile', '-File', path.join(__dirname, '..', 'tools', 'windows', 'EarthMart-NetHelper.ps1'), '-Port', String(port), '-Dir', dir], { stdio: 'inherit', env: Object.assign({}, process.env, { EM_TEST_LOCAL_MACS: '3C:52:82:1A:4F:09' }) });
  const H = 'http://127.0.0.1:' + port;
  let key = '';
  const call = async (p, body, k) => {
    const res = await fetch(H + p, { method: body ? 'POST' : 'GET', headers: Object.assign({ 'Content-Type': 'application/json' }, k !== undefined ? { 'X-EM-Key': k } : key ? { 'X-EM-Key': key } : {}), body: body ? JSON.stringify(body) : undefined });
    return Object.assign(await res.json(), { status: res.status });
  };
  for (let i = 0; i < 60; i++) { try { await call('/ping'); break; } catch (e) { await new Promise(x => setTimeout(x, 500)); } }
  try {
    let p = await call('/ping');
    assert.strictEqual(p.configured, false, 'not set up yet');
    const host = '127.0.0.1:' + r.port;
    let cap = await call('/captcha', { host });
    assert.ok(cap.ok && /^data:image\/jpeg;base64,/.test(cap.image), 'captcha picture comes back as a data URL');
    const bad = await call('/pair', { host, user: 'admin', pass: 'nope', code: r.st.code });
    assert.ok(!bad.ok && /login failed/.test(bad.error) && bad.code === 'CAPTCHA_BAD', 'wrong router password refused');
    await call('/captcha', { host });
    const badCode = await call('/pair', { host, user: 'admin', pass: 'secret', code: 'zzzz' });
    assert.ok(!badCode.ok && badCode.code === 'CAPTCHA_BAD', 'wrong captcha refused');
    await call('/captcha', { host });
    const pr = await call('/pair', { host, user: 'admin', pass: 'secret', code: r.st.code });
    assert.ok(pr.ok && pr.key, 'paired, got a key');
    key = pr.key;
    assert.deepStrictEqual(pr.devices.map(d => [d.mac, d.ip, d.name]), [['3C:52:82:1A:4F:09', '192.168.1.20', 'POS-PC'], ['A4:83:E7:22:91:BC', '192.168.1.34', 'Earth-phone'], ['D2:6F:3B:90:AE:14', '192.168.1.57', 'HUAWEI-P30'], ['46:6B:60:A4:95:88', '192.168.1.101', 'supaporn-s-Z-Flip6']], 'connected devices read; real names from the Wi-Fi topology replace android-dhcp-NN');
    assert.strictEqual((await call('/state', null, 'wrong')).status, 401, 'key required');
    let s = await call('/allow', { mac: '3c-52-82-1a-4f-09', name: 'POS หน้าร้าน' });
    assert.deepStrictEqual(s.entries.map(e => e.mac), ['3C:52:82:1A:4F:09'], 'allowed device listed');
    assert.ok(/^EM-|POS/.test(r.st.list[0].name), 'name made router-safe');
    assert.deepStrictEqual(r.st.list.map(e => e.ssid), ['SSID-1', 'SSID-5'], 'one Wi-Fi filter row per SSID (2.4G and 5G)');
    assert.deepStrictEqual(s.entries[0].ssids, ['SSID-1', 'SSID-5'], 'page gets one row per device with its SSIDs');
    s = await call('/allow', { mac: 'A4:83:E7:22:91:BC', name: 'Earth phone' });
    s = await call('/allow', { mac: 'A4:83:E7:22:91:BC', name: 'Earth phone' });
    assert.strictEqual(s.entries.length, 2, 'allowing twice keeps one entry');
    // safety: a list in blacklist mode is switched off + whitelist before anything is added
    r.st.enabled = 1; r.st.policy = 0;
    s = await call('/allow', { mac: '9C:2E:A1:00:00:07', name: 'Guest' });
    assert.deepStrictEqual([r.st.enabled, r.st.policy, s.enabled, s.policy], [0, 1, false, 'white'], 'blacklist list turned off and set to whitelist before adding');
    s = await call('/block', { mac: '9C:2E:A1:00:00:07' });
    // safety: unknown page format -> change nothing
    r.st.hideVars = true;
    const unk = await call('/allow', { mac: '9C:2E:A1:00:00:08', name: 'X' });
    assert.ok(!unk.ok && /mode unknown/.test(unk.error) && !r.st.macs().includes('9C:2E:A1:00:00:08'), 'unknown filter mode: nothing added');
    r.st.hideVars = false;
    // safety: whitelist cannot be turned on unless this PC is on every SSID
    const keep = r.st.list.slice();
    r.st.list = r.st.list.filter(e => !(e.mac === '3C:52:82:1A:4F:09' && e.ssid === 'SSID-5'));
    const lock = await call('/mode', { enabled: true });
    assert.ok(!lock.ok && /this PC is not on the list/.test(lock.error) && r.st.enabled === 0, 'refuses to lock this PC out (missing on 5G)');
    r.st.list = keep;
    s = await call('/mode', { enabled: true });
    assert.deepStrictEqual([s.enabled, s.policy, r.st.enabled, r.st.policy], [true, 'white', 1, 1], 'whitelist on');
    s = await call('/block', { mac: 'A4:83:E7:22:91:BC' });
    assert.deepStrictEqual(s.entries.map(e => e.mac), ['3C:52:82:1A:4F:09'], 'blocked device removed');
    const t = await call('/test', {});
    assert.ok(t.ok && t.steps.length === 3, 'self test: read, add, remove');
    assert.deepStrictEqual(r.st.macs(), ['3C:52:82:1A:4F:09'], 'test entry cleaned up (both SSIDs)');
    r.st.sid = 'someone-else';
    s = await call('/allow', { mac: 'D2:6F:3B:90:AE:14', name: 'P30' });
    assert.ok(!s.ok && s.code === 'CAPTCHA', 'asks for the captcha again after the router drops the session');
    s = await call('/state');
    assert.strictEqual(s.code, 'CAPTCHA', 'still waiting for the captcha');
    await call('/captcha', {});
    s = await call('/login', { code: r.st.code });
    assert.ok(s.ok && s.entries.length === 1, 'logged in again with the captcha');
    assert.strictEqual((await call('/ping')).loggedIn, true, 'ping says logged in');
    s = await call('/allow', { mac: 'D2:6F:3B:90:AE:14', name: 'P30' });
    assert.ok(s.ok && s.entries.some(e => e.mac === 'D2:6F:3B:90:AE:14'), 'works again after the captcha login');
    s = await call('/block', { mac: 'D2:6F:3B:90:AE:14' });
    r.st.noPageToken = true;
    s = await call('/allow', { mac: 'D2:6F:3B:90:AE:14', name: 'P30' });
    assert.ok(s.ok && s.entries.some(e => e.mac === 'D2:6F:3B:90:AE:14'), 'token found elsewhere when the page has none');
    s = await call('/block', { mac: 'D2:6F:3B:90:AE:14' });
    assert.ok(s.ok && !s.entries.some(e => e.mac === 'D2:6F:3B:90:AE:14'), 'remove works with the other token source');
    r.st.noPageToken = false;
    r.st.ssids = ['SSID-1'];
    s = await call('/allow', { mac: '46:6B:60:A4:95:88', name: 'Flip 6' });
    assert.ok(s.ok && r.st.list.filter(e => e.mac === '46:6B:60:A4:95:88').length === 1, 'a router without SSID-5 still takes the 2.4G row');
    s = await call('/block', { mac: '46:6B:60:A4:95:88' });
    r.st.ssids = ['SSID-1', 'SSID-5'];
    s = await call('/mode', { enabled: false });
    assert.strictEqual(s.enabled, false, 'whitelist off');
    // band choice: 5G only, then both, then 2.4G only; and the 8-per-Wi-Fi limit
    const rows = m => r.st.list.filter(e => e.mac === m).map(e => e.ssid).sort().join('+');
    s = await call('/allow', { mac: '9C:2E:A1:00:00:10', name: 'Staff', ssids: ['SSID-5'] });
    assert.strictEqual(rows('9C:2E:A1:00:00:10'), 'SSID-5', '5G only');
    s = await call('/allow', { mac: '9C:2E:A1:00:00:10', name: 'Staff', ssids: ['SSID-1', 'SSID-5'] });
    assert.strictEqual(rows('9C:2E:A1:00:00:10'), 'SSID-1+SSID-5', 'changed to both');
    s = await call('/allow', { mac: '9C:2E:A1:00:00:10', name: 'Staff', ssids: ['SSID-1'] });
    assert.strictEqual(rows('9C:2E:A1:00:00:10'), 'SSID-1', 'changed to 2.4G only (5G row removed)');
    assert.ok(s.ssidUse && s.ssidMax === 8 && s.ssidUse['SSID-1'] >= 1, 'page gets per-Wi-Fi use and the limit');
    for (let i = 0; r.st.list.filter(e => e.ssid === 'SSID-5').length < 8; i++) await call('/allow', { mac: '9C:2E:A1:00:01:' + String(i).padStart(2, '0'), name: 'F' + i, ssids: ['SSID-5'] });
    const full = await call('/allow', { mac: '9C:2E:A1:00:00:20', name: 'Ninth' });
    assert.ok(!full.ok && /wifi full: SSID-5/.test(full.error) && !r.st.macs().includes('9C:2E:A1:00:00:20'), '5G full: refused before touching the router');
    s = await call('/allow', { mac: '9C:2E:A1:00:00:20', name: 'Ninth', ssids: ['SSID-1'] });
    assert.strictEqual(rows('9C:2E:A1:00:00:20'), 'SSID-1', 'still fits on 2.4G');
    for (const m of r.st.macs().filter(m => m.startsWith('9C:2E:A1'))) await call('/block', { mac: m });
    // the real AIS page (trimmed, anonymised): on, whitelist, 5 devices each on SSID-1 and SSID-5
    r.st.rawPage = fs.readFileSync(path.join(__dirname, 'fixtures', 'wlanmacfilter-ais.asp'), 'utf8');
    s = await call('/state');
    assert.deepStrictEqual([s.enabled, s.policy, s.known], [true, 'white', true], 'real page: filter on, whitelist');
    assert.deepStrictEqual(s.entries.map(e => [e.mac, e.name, e.ssids.join('+')]), [['02:00:00:00:00:01', 'Phone A', 'SSID-1+SSID-5'], ['02:00:00:00:00:02', 'Phone B', 'SSID-1+SSID-5'], ['02:00:00:00:00:03', 'Shop PC', 'SSID-1+SSID-5'], ['02:00:00:00:00:04', 'Phone C', 'SSID-1+SSID-5'], ['02:00:00:00:00:05', 'Phone D', 'SSID-1+SSID-5']], 'real page: entries with names and both SSIDs');
    r.st.rawPage = null;
    const pb = await call('/probe', {});
    assert.ok(pb.ok && pb.pages >= 3 && pb.macPages.length >= 1, 'probe saves pages');
    const cfg = JSON.parse(fs.readFileSync(path.join(dir, 'net-config.json'), 'utf8'));
    assert.ok(!JSON.stringify(cfg).includes('secret'), 'password not stored in plain text');
    console.log('Net helper test passed');
  } finally { ps.kill(); r.server.close(); }
})().catch(e => { console.error(e); process.exit(1); });
